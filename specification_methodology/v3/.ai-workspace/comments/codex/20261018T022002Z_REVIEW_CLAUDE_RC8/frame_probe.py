"""Check affected frame copies independently, reading frozen Git objects only."""
import json
import re

from record_probe import BASELINE, SOURCE, git_bytes, sha


def without_digests(text):
    return re.sub(r'(?<=sha256=)[0-9a-f]{64}', '<digest>', text)


def owner_section(text, heading):
    lines = text.splitlines(keepends=True)
    start = next(i for i, line in enumerate(lines) if line.rstrip() == heading)
    depth = len(heading) - len(heading.lstrip('#'))
    end = next((i for i in range(start+1, len(lines))
                if re.match(r'^#{1,' + str(depth) + r'}\s', lines[i])), len(lines))
    return ''.join(lines[start:end]).strip()


def main():
    manifest = json.loads(git_bytes('standards/frames/FRAME_INPUTS.json'))
    prior = {f['id']: f for f in json.loads(git_bytes('standards/frames/FRAME_INPUTS.json', BASELINE))['frames']}
    records = []
    for frame in manifest['frames']:
        raw = git_bytes(frame['path'])
        assert sha(raw) == frame['sha256'] and len(raw) == frame['bytes'], frame['id']
        pins = frame['routes'] + frame.get('binds', [])
        for pin in pins:
            assert sha(git_bytes(pin['owner'])) == pin['owner_sha256'], (frame['id'], pin['owner'])
        now = raw.decode()
        old = git_bytes(prior[frame['id']]['path'], BASELINE).decode()
        norm_now, norm_old = without_digests(now), without_digests(old)
        only_pins = norm_now == norm_old
        if not only_pins:
            assert frame['id'] == 'dm-task-d', frame['id']
            heading = '### Proportional design sequencing'
            before, after = owner_section(old, heading), owner_section(now, heading)
            for ref, excerpt in [(BASELINE, before), (SOURCE, after)]:
                source = owner_section(git_bytes('standards/DESIGN_MODULE.md', ref).decode(), heading)
                # The affected section contains simple relative Markdown links;
                # undo their directory rebase before checking literal identity.
                assert excerpt.replace('](../', '](') == source, ref
            altered = norm_now.replace(without_digests(after), without_digests(before), 1)
            # Generated byte-count presentation changes with the new paragraph.
            strip_size = lambda t: re.sub(r'(?m)^Size of this frame: \d+ bytes\.$', '<size>', t)
            assert strip_size(altered) == strip_size(norm_old)
        records.append({'frame': frame['id'], 'bytes': len(raw), 'member_pins': len(pins),
                        'only_pin_changes': only_pins,
                        'affected_source_excerpt_identical': True if not only_pins else None})
    return {'kind': 'independent-rc8-affected-frame-probe', 'source': SOURCE,
            'baseline': BASELINE, 'passed': True, 'frames': records,
            'limits': 'All frame file identities and member pins checked; eleven copies change only digest text. The single changed source excerpt is checked literally against both owners, with relative link rebase reversed. This does not establish task sufficiency, row-selection adequacy or actual use.'}


if __name__ == '__main__':
    print(json.dumps(main(), indent=2))
