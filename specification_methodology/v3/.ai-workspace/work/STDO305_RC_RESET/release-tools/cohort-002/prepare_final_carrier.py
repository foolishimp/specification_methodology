"""Freeze one exact final carrier stage after local acceptance; no Git/index mutation."""
import hashlib
import json
import os
import stat
import subprocess
from pathlib import Path
R = Path.cwd()
Q = R / 'specification_methodology/v3/.ai-workspace/work/STDO305_RC_RESET'
W = Q / 'release-tools'
C = Path(__file__).resolve().parent
O = C / 'final-carrier'
sha = lambda b: hashlib.sha256(b).hexdigest()
def load(p): return json.loads(p.read_bytes())
def ref(p):
    raw = p.read_bytes(); return {'path': p.relative_to(R).as_posix(), 'sha256': sha(raw), 'bytes': len(raw)}
def save(p, value):
    p.parent.mkdir(parents=True, exist_ok=True)
    with p.open('x') as f: json.dump(value, f, indent=2, sort_keys=True); f.write('\n')
    return ref(p)
def git(*argv): return subprocess.check_output(['git', '--no-optional-locks', *argv], cwd=R)
assert git('rev-parse', 'HEAD').decode().strip() == '71844a9e9b52df56c842f81afa44f050ec8424cf'
assert not git('diff', '--cached', '--name-only')
assert not O.exists()
manifest = load(R / 'stack_release.json')
assert manifest['cohort']['status'] == 'complete' and manifest['cohort']['cut'] == 'v3.0.5-rc.1'
acceptance = load(C / 'LOCAL_ACCEPTANCE.json')
assert acceptance['disposition'] == 'accepted_for_release_scope'
tools_index_path = Q / 'tools-skills/evidence-custody-002/INDEX_002.json'
tools_index = load(tools_index_path)
tools_rows = tools_index['eligible']
paths = {row['path'] for row in tools_rows} | {str(p.relative_to(R)) for p in tools_index_path.parent.iterdir() if p.is_file()} | {'stack_release.json'}
untracked = [x.decode() for x in git('ls-files', '--others', '--exclude-standard', '-z', '--', str(Q.relative_to(R))).split(b'\0') if x]
excluded = []
for name in untracked:
    relative = Path(name).relative_to(Q.relative_to(R)).as_posix()
    if relative.startswith('tools-skills/'):
        if name not in paths: excluded.append({'path': name, 'reason': 'Owner custody exclusion or separately pending preparation; preserved locally.'})
        continue
    if relative == 'release-tools/packaging-001/archives/current.zip' or relative.endswith('/proof-retention/archives/full.zip'):
        excluded.append({'path': name, 'reason': 'Oversized duplicate ZIP; exact complete multipart descriptor/parts selected.'}); continue
    if relative.startswith('release-tools/anchor-repair-005/tooling/'):
        excluded.append({'path': name, 'reason': 'Generated byte duplicate of already committed current common/standards/tooling member.'}); continue
    if relative.endswith('/native-index'):
        excluded.append({'path': name, 'reason': 'Private isolated Git index; exact native object/source/operation receipts selected.'}); continue
    assert relative.startswith(('release-tools/', 'native-release/')), relative
    paths.add(name)
tracked = {x.decode() for x in git('ls-files', '-z').split(b'\0') if x}
changed = {x.decode() for x in git('diff', '--name-only', '-z').split(b'\0') if x}
assert changed <= {'stack_release.json'}, changed
paths = {name for name in paths if name not in tracked or name in changed}
selection = save(O / 'SELECTION.json', {'kind': 'stdo.final-carrier-closed-selection/1', 'tools_custody': ref(tools_index_path),
    'ordinary_paths': sorted(paths), 'excluded_preserved': excluded, 'acceptance': ref(C / 'LOCAL_ACCEPTANCE.json'),
    'limits': 'Only closed reset delivery evidence and final B; no Product/native/source change, global installation, cleanup or other release effect.'})
rows = []
for name in sorted(paths):
    p = R / name; st = p.lstat(); assert stat.S_ISREG(st.st_mode) and not p.is_symlink(), name
    raw = p.read_bytes(); assert len(raw) < 100 * 1024**2, name
    rows.append({'path': name, 'bytes': len(raw), 'sha256': sha(raw), 'git_mode': '100755' if st.st_mode & 0o111 else '100644',
        'git_blob': hashlib.sha1(b'blob ' + str(len(raw)).encode() + b'\0' + raw).hexdigest()})
path_ref = save(O / 'PATHS.json', {'files': rows, 'bytes': sum(row['bytes'] for row in rows), 'count': len(rows), 'selection': selection})
controls = [O / name for name in ('SELECTION.json', 'PATHS.json', 'stage-paths.z', 'PLAN.json')]
nul = O / 'stage-paths.z'; nul.write_bytes(b''.join(name.encode() + b'\0' for name in sorted(paths | {str(p.relative_to(R)) for p in controls})))
logical = sha(git('ls-files', '-s', '-z'))
plan = save(O / 'PLAN.json', {'kind': 'stdo.final-rc-carrier-plan/1', 'head': '71844a9e9b52df56c842f81afa44f050ec8424cf',
    'branch': 'refs/heads/main', 'index_logical_sha256': logical, 'paths': path_ref, 'nul': ref(nul), 'controls': [str(p.relative_to(R)) for p in controls],
    'commit_message': 'Release STDO 3.0.5 RC1 cohort and reset unadopted selectors', 'free_space_floor_bytes': 2 * 1024**3,
    'manifest': ref(R / 'stack_release.json'), 'acceptance': ref(C / 'LOCAL_ACCEPTANCE.json'),
    'publication_operations': ref(C / 'publication/OPERATION_TEMPLATES.json'), 'publication_executor': ref(C / 'execute_publication.py'),
    'authority': 'Owner explicitly authorized reset, commit/push/publication; Root assigned this sole Writer to dependency-ready checked steps without another confirmation. Exact 16-ref atomic vector only; unchanged successful steps continue.',
    'whitespace': 'Preserve frozen original/generated/historical evidence bytes; authored live source defects refuse. No blanket ignore.',
    'scope': 'One carrier D; four create-only peer RC tags, five create-only old-object archive refs, five exact leased selectors; refs(D) includes ready/content predicates; emitted atomic push only, normal five-asset release, prescribed published/public and Latest sequence.'})
print(json.dumps({'plan': plan, 'paths': path_ref, 'nul': ref(nul), 'index': logical, 'payload_files': len(rows), 'stage_paths': len(paths) + 4, 'bytes': sum(row['bytes'] for row in rows)}))
