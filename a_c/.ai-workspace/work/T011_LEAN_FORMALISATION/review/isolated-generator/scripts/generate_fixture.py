#!/usr/bin/env python3
"""Deterministic bridge from independently checked fixture bytes to Lean data.

The generator is not trusted to prove closure: emitted checks use `decide +kernel`
and generic soundness theorems. JSON decoding/schema extraction remains outside
Lean; `--check` detects any drift of the checked-in source-bound import artifact.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
from import_fixture import (
    FIXTURE_DIR, RAW_SHA256, canonical, closure_certificate, import_model,
    load_checked, verify_fixture, TOY_FIXTURE_DIR, TOY_RAW_SHA256,
)

ROOT = Path(__file__).resolve().parents[1]

def lean_string(value: str) -> str:
    escapes = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}
    return '"' + ''.join(escapes.get(ch, f"\\u{{{ord(ch):x}}}" if ord(ch) < 32 or ord(ch) == 127 else ch) for ch in value) + '"'

def numbers(values) -> str:
    return '[' + ', '.join(str(n) for n in values) + ']'

def source_data(imported: dict, raw_sha: str) -> str:
    out = []
    for entry in imported['records']:
        r, i = entry['record'], entry['index']
        out.append(f'def record{i} : Record := {{\n  key := {i}\n  family := .{entry["family"]}')
        for field, value in [('identity',r['id']),('context',r['context']),('owner',r['owner']),
                             ('scope',canonical(r['scope'])),('basis',r['basis']),('payload',canonical(r))]:
            out.append(f'  {field} := {lean_string(value)}')
        out.append('}\n')
    refs = []
    for ref in imported['references']:
        path = '[' + ', '.join(f'.index {v}' if type(v) is int else f'.field {lean_string(v)}' for v in ref['path']) + ']'
        target = f'.localRecord {ref["target"]}' if type(ref['target']) is int else f'.external {lean_string(ref["target"])}'
        refs.append(f'  {{ owner := {ref["owner"]}, path := {path}, target := {target}, governing := {str(ref["governing"]).lower()}, domain := {lean_string(ref["domain"])} }}')
    externals = [f'  {{ identity := {lean_string(e["external_identity"])}, payload := {lean_string(canonical(e))} }}' for e in imported['envelope']['external_resolutions']]
    out += ['def model : Model := {',f'  identity := {lean_string(imported["envelope"]["id"])}',
            f'  rawSha256 := {lean_string(raw_sha)}', f'  canonicalSha256 := {lean_string(imported["model_sha256"])}',
            f'  envelope := {lean_string(canonical(imported["envelope"]))}',
            '  records := [' + ', '.join(f'record{e["index"]}' for e in imported['records']) + ']',
            '  references := [\n' + ',\n'.join(refs) + '\n  ]',
            '  externalResolutions := [\n' + ',\n'.join(externals) + '\n  ]',
            '  edges := [' + ', '.join(f'({a}, {b})' for a,b in imported['edges']) + ']',
            f'  invalidation := {lean_string(canonical(imported["envelope"]["interpretation"]["invalidation"]))}',
            '}\n', 'theorem model_checked : checkModel model = true := by decide +kernel\n']
    return '\n'.join(out)

def case_source(certificate: dict, name: str) -> str:
    i, seeds, order, included, size = name, certificate['seeds'], certificate['order'], certificate['included'], certificate['required_count']
    return f'''def seeds{i} : Finset Nat := ({numbers(seeds)} : List Nat).toFinset

def trace{i} : List Nat := {numbers(order)}

def included{i} : Finset Nat := ({numbers(included)} : List Nat).toFinset

theorem checked{i} : checkCertificate model.dependencies model.localKeys seeds{i} trace{i} = true := by decide +kernel

theorem set{i} : traceSet seeds{i} trace{i} = included{i} := by decide +kernel

theorem reachability{i} (x : Nat) : x ∈ included{i} ↔ Reachable model.dependencies seeds{i} x := by
  rw [← set{i}]
  exact certificate_exact_reachability model.dependencies model.localKeys seeds{i} trace{i} checked{i} x

theorem success{i} : project model seeds{i} trace{i} {size} = .ok (makeProjection model seeds{i} included{i}) := by
  rw [← set{i}]
  exact projection_success model seeds{i} trace{i} {size} model_checked checked{i} (by decide +kernel)

theorem budget_refusal{i} : project model seeds{i} trace{i} {size-1} =
    .error "insufficient record budget; required closure is not truncated" :=
  insufficient_budget_refuses model seeds{i} trace{i} {size-1} model_checked checked{i} (by decide +kernel)
'''

def generate(imported: dict, raw_sha: str, cases: list[dict], namespace: str = 'AC.Fixture') -> str:
    header = f'''module
public import AC.Projection

/-! Generated by scripts/generate_fixture.py. Complete canonical source payloads
are retained. The source-byte/import mapping is tested but not Lean-proved.
All concrete decisions below are reduced by the Lean kernel, not native_decide. -/
@[expose] public section
set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option debug.skipKernelTC false
namespace {namespace}

'''
    body = source_data(imported, raw_sha)
    body += '\n' + '\n'.join(case_source(c, str(i)) for i,c in enumerate(cases))
    body += '\ndef selections : List (Finset Nat × List Nat × Nat) := [\n'
    body += ',\n'.join(f'  (seeds{i}, trace{i}, {c["required_count"]})' for i,c in enumerate(cases)) + '\n]\n'
    return header + body + f'\nend {namespace}\n'

def expected_source() -> tuple[str, dict]:
    custody = verify_fixture()
    imported = import_model(load_checked(FIXTURE_DIR / 'MODEL.json'))
    cases = [closure_certificate(imported, [i]) for i in range(len(imported['records']))]
    return generate(imported, RAW_SHA256['MODEL.json'], cases), custody

def main() -> int:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    content,custody=expected_source()
    toy_path = TOY_FIXTURE_DIR/'MODEL.json'
    if hashlib.sha256(toy_path.read_bytes()).hexdigest() != TOY_RAW_SHA256:
        raise SystemExit('All-family toy fixture raw digest mismatch')
    toy = import_model(load_checked(toy_path))
    toy_cases = [closure_certificate(toy,[i]) for i in range(len(toy['records']))]
    outputs = {'Fixture':content, 'Toy':generate(toy,TOY_RAW_SHA256,toy_cases,'AC.Toy')}
    for name, generated in outputs.items():
        target=ROOT/f'AC/{name}.lean'
        if args.check:
            if not target.exists() or target.read_text()!=generated:
                raise SystemExit(f'Generated Lean {name} differs from exact checked source import')
        else:
            target.write_text(generated)
    print(json.dumps({'status':'source-bound-import-checked' if args.check else 'generated',
                      'lean_source_sha256':hashlib.sha256(content.encode()).hexdigest(),
                      'source':custody,'toy_records':len(toy['records']),
                      'toy_lean_source_sha256':hashlib.sha256(outputs['Toy'].encode()).hexdigest()},ensure_ascii=False,sort_keys=True))
    return 0

if __name__=='__main__':
    raise SystemExit(main())
